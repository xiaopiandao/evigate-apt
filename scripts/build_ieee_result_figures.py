"""Build the data-driven IEEE result figures with SciPilot QA.

The script intentionally covers only quantitative figures.  The system
architecture diagram remains generated by ``build_stage4_figures.py`` because
SciPilot's figure skill is scoped to scientific data visualizations.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
from pathlib import Path
import shutil
import sys
from typing import Any

import matplotlib as mpl

mpl.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SKILL_DIR = (
    Path(os.environ.get("USERPROFILE", Path.home()))
    / ".codex"
    / "skills"
    / "scipilot-figure-skill"
)

RULES = ("confidence", "margin", "controller", "dual")
RULE_LABELS = {
    "confidence": "Confidence",
    "margin": "Posterior margin",
    "controller": "Controller",
    "integrity": "Integrity",
    "dual": "Dual",
}
RULE_STYLES = {
    "confidence": {"color": "#0072B2", "marker": "o", "linestyle": "-"},
    "margin": {"color": "#222222", "marker": "v", "linestyle": (0, (4, 2))},
    "controller": {"color": "#E69F00", "marker": "s", "linestyle": "--"},
    "integrity": {"color": "#009E73", "marker": "^", "linestyle": "-."},
    "dual": {"color": "#CC79A7", "marker": "D", "linestyle": ":"},
}


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def add_margin_frontier(rows: list[dict[str, str]]) -> list[dict[str, Any]]:
    """Add the prespecified margin comparator without changing frozen diagnostics."""
    if any(row["rule"] == "margin" for row in rows):
        return rows
    from build_stage4_diagnostics import bootstrap_curve_point
    from run_stage_c_selective_attribution import risk_for, selection_mask

    source = read_csv(
        ROOT / "data" / "derived" / "stage4_revision" / "stage_c_selector_baselines"
        / "stage_c_selector_baselines.test_predictions.csv"
    )
    assert len(source) == 53 and len({row["case_id"] for row in source}) == 53
    cases = [
        {"case_id": row["case_id"], "correct": int(row["correct"]), "margin_score": float(row["margin_score"])}
        for row in source
    ]
    for index, requested in enumerate(np.linspace(0.1, 1.0, 10)):
        count = max(1, int(round(float(requested) * len(cases))))
        accepted = selection_mask(cases, "margin_score", count)
        interval = bootstrap_curve_point(cases, "margin_score", count, 10000, 20260915 + 5000 + index)
        rows.append({
            "rule": "margin",
            "requested_coverage": float(requested),
            "accepted_events": count,
            "realized_coverage": count / len(cases),
            "risk": risk_for(cases, accepted),
            "cluster_bootstrap_ci95_lower": interval[0],
            "cluster_bootstrap_ci95_upper": interval[1],
            "bootstrap_iterations": 10000,
        })
    return rows


def load_scipilot(skill_dir: Path):
    scripts_dir = skill_dir / "scripts"
    if not scripts_dir.is_dir():
        raise FileNotFoundError(
            f"SciPilot scripts not found at {scripts_dir}; pass --skill-dir explicitly"
        )
    sys.path.insert(0, str(scripts_dir))
    from export_figure import export_figure
    from layout_tools import add_panel_labels, finalize_figure
    from setup_style import setup_style
    from visual_qa import audit_layout, print_report, render_preview

    return setup_style, export_figure, finalize_figure, add_panel_labels, audit_layout, print_report, render_preview


def style_ieee(setup_style) -> dict[str, Any]:
    info = setup_style(
        journal="ieee",
        lang="en",
        use_sciplots=False,
        constrained_layout=True,
    )
    # Preserve the IEEE preset while strengthening final-size legibility.
    mpl.rcParams.update(
        {
            "font.size": 8,
            "axes.labelsize": 8,
            "axes.titlesize": 8.5,
            "legend.fontsize": 7,
            "xtick.labelsize": 7,
            "ytick.labelsize": 7,
            "lines.linewidth": 1.15,
            "lines.markersize": 4.2,
            "axes.unicode_minus": False,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "svg.fonttype": "none",
        }
    )
    return info


def grid_y(ax: plt.Axes) -> None:
    ax.set_axisbelow(True)
    ax.grid(axis="y", color="#D6D6D6", linewidth=0.45, linestyle=":")


def build_operating_frontiers_figure(
    source_dir: Path,
    out_stem: Path,
    tools: tuple,
) -> dict[str, Any]:
    _, export_figure, finalize_figure, add_panel_labels, audit_layout, print_report, render_preview = tools
    risk_rows = add_margin_frontier(read_csv(source_dir / "figure2a_risk_coverage.csv"))
    write_csv(source_dir / "figure2a_risk_coverage.csv", risk_rows)
    write_csv(ROOT / "paper" / "figures" / "source_data" / "figure2a_risk_coverage.csv", risk_rows)
    retention_rows = sorted(
        read_csv(source_dir / "figure2b_retention_frontier.csv"),
        key=lambda row: float(row["false_alert_budget_per_hour"]),
    )

    fig, (ax1, ax2) = plt.subplots(
        1,
        2,
        figsize=(7.16, 2.85),
        gridspec_kw={"width_ratios": (1.28, 1.0)},
        constrained_layout=True,
    )

    for rule in RULES:
        rows = sorted(
            (row for row in risk_rows if row["rule"] == rule),
            key=lambda row: float(row["realized_coverage"]),
        )
        x = np.asarray([float(row["realized_coverage"]) for row in rows])
        y = np.asarray([float(row["risk"]) for row in rows])
        lo = np.asarray([float(row["cluster_bootstrap_ci95_lower"]) for row in rows])
        hi = np.asarray([float(row["cluster_bootstrap_ci95_upper"]) for row in rows])
        style = RULE_STYLES[rule]
        ax1.fill_between(x, lo, hi, color=style["color"], alpha=0.075, linewidth=0)
        ax1.plot(
            x,
            y,
            label=RULE_LABELS[rule],
            color=style["color"],
            marker=style["marker"],
            linestyle=style["linestyle"],
            markerfacecolor="white",
            markeredgewidth=0.8,
            zorder=3,
        )
    fixed = 42 / 53
    ax1.axvline(fixed, color="#555555", linestyle=(0, (3, 2)), linewidth=0.8)
    ax1.text(
        fixed - 0.012,
        0.77,
        "fixed 42/53",
        rotation=90,
        ha="right",
        va="top",
        fontsize=7,
        color="#444444",
    )
    ax1.set_xlim(0.07, 1.015)
    ax1.set_ylim(0, 1.02)
    ax1.set_xticks(np.arange(0.2, 1.01, 0.2))
    ax1.set_yticks(np.arange(0, 1.01, 0.2))
    ax1.set_xlabel("Realized coverage")
    ax1.set_ylabel("Selective labeling risk")
    ax1.set_title("Risk changes with the operating point", fontweight="bold")
    ax1.legend(
        loc="upper right",
        ncol=2,
        frameon=False,
        handlelength=2.0,
        columnspacing=0.8,
        borderaxespad=0.35,
    )
    grid_y(ax1)

    retained_bytes = np.asarray(
        [float(row["retained_timestamped_byte_fraction"]) for row in retention_rows]
    )
    event_coverage = np.asarray(
        [float(row["mean_all_event_coverage"]) for row in retention_rows]
    )
    budgets = [float(row["false_alert_budget_per_hour"]) for row in retention_rows]
    ax2.plot(
        retained_bytes,
        event_coverage,
        color="#0072B2",
        marker="o",
        markerfacecolor="white",
        markeredgecolor="#003F5C",
        markeredgewidth=0.9,
        linewidth=1.3,
        zorder=3,
    )
    label_offsets = [(-7, -13), (9, -1), (8, 6), (-7, 9)]
    for x, y, budget, offset in zip(
        retained_bytes, event_coverage, budgets, label_offsets
    ):
        ax2.annotate(
            f"{budget:g}",
            (x, y),
            xytext=offset,
            textcoords="offset points",
            ha="center",
            va="center",
            fontsize=7,
            fontweight="bold",
            color="#222222",
        )
    ax2.set_xlim(0, 0.42)
    ax2.set_ylim(0, 1.02)
    ax2.set_xticks(np.arange(0, 0.41, 0.1))
    ax2.set_yticks(np.arange(0, 1.01, 0.2))
    ax2.set_xlabel("Retained timestamped CSV-byte fraction")
    ax2.set_ylabel("All-event network coverage")
    ax2.set_title("Coverage--retention frontier", fontweight="bold")
    ax2.text(
        0.18,
        0.96,
        "point labels: calibration budget (false alerts/h)",
        transform=ax2.transAxes,
        ha="left",
        va="top",
        fontsize=6.7,
        color="#444444",
    )
    ax2.text(
        0.05,
        0.07,
        "End to end ($n=51$)\n"
        "18 correct  |  6 wrong\n"
        "12 unattributed  |  15 no alert",
        transform=ax2.transAxes,
        ha="left",
        va="bottom",
        fontsize=6.8,
        color="#222222",
        linespacing=1.25,
        bbox={
            "boxstyle": "round,pad=0.32",
            "facecolor": "white",
            "edgecolor": "#777777",
            "linewidth": 0.55,
            "alpha": 0.96,
        },
    )
    grid_y(ax2)

    finalize_figure(fig)
    add_panel_labels(
        fig,
        axes=[ax1, ax2],
        style="ieee",
        fontsize=9,
        x_offset_pt=3,
        y_offset_pt=-3,
        ha="left",
        va="top",
    )
    issues = audit_layout(fig)
    verdict = print_report(issues)
    preview = render_preview(fig, str(out_stem) + "_preview.png", dpi=180)
    paths = export_figure(
        fig,
        str(out_stem),
        formats=("pdf", "svg", "png", "tiff"),
        dpi=600,
        size_inches=(7.16, 2.85),
        grayscale_preview=True,
        tight=False,
    )
    plt.close(fig)
    return {"verdict": verdict, "issues": issues, "preview": preview, "paths": paths}


def build_robustness_figure(
    bind_summary_path: Path,
    out_stem: Path,
    source_dir: Path,
    tools: tuple,
) -> dict[str, Any]:
    _, export_figure, finalize_figure, _, audit_layout, print_report, render_preview = tools
    bind = json.loads(bind_summary_path.read_text(encoding="utf-8"))
    audit = json.loads(
        (ROOT / "data" / "derived" / "reviewer_p0" / "reviewer_p0_audit.json").read_text(encoding="utf-8")
    )["three_family_group_audit"]
    assert bind["events"] == audit["events"] == 51
    estimands = audit["effects"]
    effect_specs = [
        ("Three-family\nwrong-label", "three_family"),
        ("Foreign-context\nwrong-label", "context"),
        ("Five-family\nwrong-label", "five_family"),
        ("Clean selective\nrisk", "clean_risk"),
    ]
    effect_rows: list[dict[str, Any]] = []
    for metric, key in effect_specs:
        item = estimands[key]
        effect_rows.append(
            {
                "metric": metric.replace("\n", " "),
                "estimate": float(item["observed"]),
                "ci95_lower": float(item["group_bootstrap_ci95"][0]),
                "ci95_upper": float(item["group_bootstrap_ci95"][1]),
                "bootstrap_unit": "embargo group",
                "bootstrap_iterations": audit["resamples"],
                "n_events": audit["events"],
                "n_groups": audit["embargo_groups"],
            }
        )

    fig, ax1 = plt.subplots(figsize=(7.16, 2.55), constrained_layout=True)

    y = np.arange(len(effect_rows))
    estimates = np.asarray([row["estimate"] for row in effect_rows])
    lower = np.asarray([row["ci95_lower"] for row in effect_rows])
    upper = np.asarray([row["ci95_upper"] for row in effect_rows])
    for idx, row in enumerate(effect_rows):
        excludes_zero = row["ci95_lower"] > 0 or row["ci95_upper"] < 0
        ax1.errorbar(
            row["estimate"],
            idx,
            xerr=np.asarray(
                [[row["estimate"] - row["ci95_lower"]], [row["ci95_upper"] - row["estimate"]]]
            ),
            fmt="o" if excludes_zero else "s",
            color="#0072B2",
            ecolor="#0072B2",
            markerfacecolor="#0072B2" if excludes_zero else "white",
            markeredgecolor="#003F5C",
            markeredgewidth=0.8,
            markersize=5.2,
            elinewidth=1.25,
            capsize=2.5,
            capthick=0.9,
            zorder=3,
        )
        ax1.text(
            row["ci95_upper"] + 0.018,
            idx,
            f'{row["estimate"]:.3f}',
            ha="left",
            va="center",
            fontsize=7,
        )
    ax1.axvline(0, color="#444444", linewidth=0.8, linestyle=(0, (3, 2)))
    ax1.set_yticks(y, [metric for metric, _ in effect_specs])
    ax1.invert_yaxis()
    ax1.set_xlim(-0.055, 0.735)
    ax1.set_xticks([0.0, 0.2, 0.4, 0.6])
    ax1.set_xlabel("Absolute reduction in adverse rate")
    ax1.set_title("CICAPT-IIoT: adverse-rate reduction over matched margin", fontweight="bold")
    grid_y(ax1)

    finalize_figure(fig)
    issues = audit_layout(fig)
    verdict = print_report(issues)
    preview = render_preview(fig, str(out_stem) + "_preview.png", dpi=180)
    paths = export_figure(
        fig,
        str(out_stem),
        formats=("pdf", "svg", "png", "tiff"),
        dpi=600,
        size_inches=(7.16, 2.55),
        grayscale_preview=True,
        tight=False,
    )
    plt.close(fig)

    write_csv(source_dir / "figure3_effect_estimates.csv", effect_rows)
    return {"verdict": verdict, "issues": issues, "preview": preview, "paths": paths}


def copy_manuscript_assets(bundle_dir: Path, manuscript_dir: Path) -> None:
    manuscript_dir.mkdir(parents=True, exist_ok=True)
    mapping = {
        "figure2_operating_frontiers": "figure2_operating_frontiers",
        "figure3_robustness_effect": "figure5_robustness_effect",
    }
    for bundle_name, manuscript_name in mapping.items():
        for suffix in (".pdf", ".svg", ".png", ".tiff"):
            shutil.copy2(bundle_dir / f"{bundle_name}{suffix}", manuscript_dir / f"{manuscript_name}{suffix}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skill-dir", type=Path, default=DEFAULT_SKILL_DIR)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "output" / "figures" / "ieee",
    )
    parser.add_argument(
        "--manuscript-figure-dir",
        type=Path,
        default=ROOT / "paper" / "figures",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    tools = load_scipilot(args.skill_dir.resolve())
    style_info = style_ieee(tools[0])
    args.output_dir.mkdir(parents=True, exist_ok=True)
    source_dir = args.output_dir / "source_data"
    source_dir.mkdir(parents=True, exist_ok=True)

    # Preserve the profiled inputs beside the final graphics.
    for name in (
        "figure2a_risk_coverage.csv",
    ):
        shutil.copy2(args.manuscript_figure_dir / "source_data" / name, source_dir / name)
    retention_source = (
        ROOT / "data" / "derived" / "p1_diagnostics" / "retention_frontier.csv"
    )
    shutil.copy2(retention_source, source_dir / "figure2b_retention_frontier.csv")
    shutil.copy2(
        retention_source,
        args.manuscript_figure_dir / "source_data" / "figure2b_retention_frontier.csv",
    )

    report = {
        "style": style_info,
        "figure2": build_operating_frontiers_figure(
            source_dir,
            args.output_dir / "figure2_operating_frontiers",
            tools,
        ),
        "figure3": build_robustness_figure(
            ROOT
            / "data"
            / "derived"
            / "evigate_llm"
            / "v7_bindgate"
            / "evaluation_temporal"
            / "evigate_bindgate.summary.json",
            args.output_dir / "figure3_robustness_effect",
            source_dir,
            tools,
        ),
    }
    (args.output_dir / "qa_report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    copy_manuscript_assets(args.output_dir, args.manuscript_figure_dir)
    print(json.dumps({"status": "ok", "output_dir": str(args.output_dir)}, indent=2))


if __name__ == "__main__":
    main()
